def apply_smart_acting_turn(
    pose: HeadPose3D,
    eye_spec: AestheticEyeSpec,
    requested_delta_yaw_deg: float = 0.0,
    requested_delta_pitch_deg: float = 0.0,
) -> tuple[HeadPose3D, AestheticEyeSpec]:
    """
    Enforce the user's Smart Anatomical Head-vs-Gaze Rule:
      * When the character's neck does NOT rotate in the underlying image/frame, the face (`eyes_mid`, `mouth`)
        cannot slide into the ear! Any head micro-turn is clamped to `pose.max_acting_shift_px` (default 8.0 px, ~3.2 deg).
      * Any leftover requested look angle beyond that 8 px micro-drift is automatically transferred into `eye_spec.gaze_x`
        and `eye_spec.gaze_y` so the pupils turn inside the almond eye sockets while the face stays anatomically locked!
    """
    max_rad = math.asin(np.clip(pose.max_acting_shift_px / max(pose.R, 20.0), 0.02, 0.085))
    req_dyaw = math.radians(requested_delta_yaw_deg)
    req_dpitch = math.radians(requested_delta_pitch_deg)

    clamped_dyaw = float(np.clip(req_dyaw, -max_rad, max_rad))
    clamped_dpitch = float(np.clip(req_dpitch, -max_rad * 0.8, max_rad * 0.8))

    excess_yaw = req_dyaw - clamped_dyaw
    excess_pitch = req_dpitch - clamped_dpitch
    new_gaze_x = float(np.clip(eye_spec.gaze_x + excess_yaw * 1.45, -0.62, 0.62))
    new_gaze_y = float(np.clip(eye_spec.gaze_y + excess_pitch * 1.25, -0.45, 0.45))

    new_pose = replace(
        pose,
        yaw=pose.base_yaw + clamped_dyaw,
        pitch=pose.base_pitch + clamped_dpitch,
    )
    new_eye = replace(eye_spec, gaze_x=new_gaze_x, gaze_y=new_gaze_y)
    return new_pose, new_eye


