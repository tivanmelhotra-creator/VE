@dataclass
class HeadPose3D:
    """Tracked 3D spherical pose of the character's physical head in screen space."""
    cx: float
    cy: float
    R: float
    yaw: float                 # Effective yaw (radians): locked to base_yaw +/- clamped micro-acting drift
    pitch: float               # Effective pitch (radians): locked to base_pitch +/- clamped micro-acting drift
    roll: float                # Head tilt angle (radians)
    stroke_px: float
    face_bgr: tuple[int, int, int] = (251, 252, 252)
    ex: float = 0.34           # Canonical half-interocular spacing on unit sphere
    ey: float = 0.01           # Canonical eye Y on unit sphere
    er: float = 0.248          # Canonical eye horizontal radius (wider for sleek almond eyes!)
    eh: float = 0.186          # Canonical eye vertical radius (`er / eh = 1.33` horizontal almond proportion)
    my: float = 0.45           # Canonical mouth Y on unit sphere
    mw: float = 0.54           # Canonical mouth base width on unit sphere
    base_yaw: float = 0.0      # Physical neck/head yaw detected from frame anatomy
    base_pitch: float = 0.0    # Physical neck/head pitch detected from frame anatomy
    base_roll: float = 0.0     # Physical neck/head roll detected from frame anatomy
    ear_safe_u_min: float = -0.78  # Left canonical safe boundary (prevents sliding into left ear/contour)
    ear_safe_u_max: float = 0.78   # Right canonical safe boundary (prevents sliding into right ear/contour)
    max_acting_shift_px: float = 8.0  # Max allowed facial drift (in pixels) when neck doesn't rotate


def _rot_matrix(yaw: float, pitch: float, roll: float) -> np.ndarray:
    cy, sy = math.cos(yaw), math.sin(yaw)
    cp, sp = math.cos(pitch), math.sin(pitch)
    cr, sr = math.cos(roll), math.sin(roll)
    Ry = np.array([[cy, 0.0, sy], [0.0, 1.0, 0.0], [-sy, 0.0, cy]])
    Rx = np.array([[1.0, 0.0, 0.0], [0.0, cp, sp], [0.0, -sp, cp]])
    Rz = np.array([[cr, -sr, 0.0], [sr, cr, 0.0], [0.0, 0.0, 1.0]])
    return Rz @ Rx @ Ry


def project_canonical(pose: HeadPose3D, uv: np.ndarray, lift_z: float = 1.0) -> tuple[np.ndarray, np.ndarray]:
    """
    Lift 2D canonical front-face points uv (N, 2) onto the 3D unit sphere and project to screen pixels,
    enforcing the Anatomical Ear/Contour Safe-Zone so features never cross into the ear.
    """
    p = np.asarray(uv, dtype=np.float64).reshape(-1, 2).copy()
    p[:, 0] = np.clip(p[:, 0], pose.ear_safe_u_min, pose.ear_safe_u_max)
    r2 = (p[:, 0] ** 2) + (p[:, 1] ** 2)
    scale = np.where(r2 > 0.94, 0.96 / np.sqrt(np.maximum(r2, 1e-12)), 1.0)
    xy = p * scale[:, None]
    z = np.sqrt(np.clip(1.0 - (xy[:, 0] ** 2 + xy[:, 1] ** 2), 0.0, 1.0)) * lift_z
    pts3 = np.c_[xy[:, 0], xy[:, 1], z]
    rot = _rot_matrix(pose.yaw, pose.pitch, pose.roll)
    q = pts3 @ rot.T
    scr = np.c_[pose.cx + pose.R * q[:, 0], pose.cy + pose.R * q[:, 1]]
    return scr, q[:, 2]


def track_head_pose_3d(
    info: dict[str, Any],
    prev: HeadPose3D | None = None,
    smooth: float = 0.0,
    max_acting_shift_px: float = 8.0,
) -> HeadPose3D:
    """
    Solve the physical 3D head sphere center (cx, cy), radius R, and physical neck/head orientation
    (base_yaw, base_pitch, base_roll) from `detect_face_anatomy(img)`, plus compute the Ear Safe-Zone.
    """
    hm = (info["head_mask_full"] > 0).astype(np.uint8)
    cs, _ = cv2.findContours(hm, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    c = max(cs, key=cv2.contourArea)
    if len(c) >= 5:
        (hcx, hcy), (A, B), _ = cv2.fitEllipse(c)
        R = 0.25 * (A + B)
    else:
        (hcx, hcy), R = cv2.minEnclosingCircle(c)
    hcx, hcy, R = float(hcx), float(hcy), max(10.0, float(R))

    emx, emy = info["eyes_mid"]
    io = float(info["inter_ocular"])
    roll = math.radians(float(info.get("eye_angle_deg", 0.0)))

    cr, sr = math.cos(-roll), math.sin(-roll)
    dx_e = (emx - hcx) / R
    dy_e = (emy - hcy) / R
    ux_e = cr * dx_e - sr * dy_e
    uy_e = sr * dx_e + cr * dy_e

    if info.get("mouth_found"):
        mx, my_px = info["mouth_center"]
        dx_m = (mx - hcx) / R
        dy_m = (my_px - hcy) / R
        ux_m = cr * dx_m - sr * dy_m
        ux_face = 0.65 * ux_e + 0.35 * ux_m
    else:
        ux_face = ux_e

    yaw = float(math.asin(np.clip(ux_face * 1.15, -0.82, 0.82)))
    cos_yaw = max(0.38, math.cos(yaw))

    ex = float(np.clip((0.5 * io / R) / cos_yaw, 0.27, 0.37))
    ey = float(np.clip(uy_e - 0.01, -0.15, 0.15))
    pitch = float(np.clip((uy_e - 0.01) * 0.50, -0.38, 0.38))

    # Sleek horizontal almond proportions (`er > eh`, ratio ~1.34)
    efills = info.get("eye_fills", [])
    if efills:
        eh_mean = float(np.mean([ef["box"][3] for ef in efills]))
        eh_raw = float(np.clip(0.47 * eh_mean / R, 0.17, 0.215))
        er = float(np.clip(eh_raw * 1.34, 0.225, 0.270))
        eh = float(er / 1.34)
    else:
        er = float(np.clip(0.73 * ex, 0.23, 0.265))
        eh = float(er / 1.34)

    if info.get("mouth_found"):
        _, mcy = info["mouth_center"]
        dy_m = (mcy - hcy) / R
        uy_m = sr * ((info["mouth_center"][0] - hcx) / R) + cr * dy_m
        my = float(np.clip(uy_m, ey + eh + 0.17, 0.62))
    else:
        my = float(np.clip(ey + eh + 0.24, 0.40, 0.60))

    mw = float(np.clip(1.56 * ex, 0.46, 0.62))

    ear_safe_u_min = -0.78 if yaw <= 0.05 else max(-0.66, -0.78 + 0.22 * math.sin(yaw))
    ear_safe_u_max = 0.78 if yaw >= -0.05 else min(0.66, 0.78 + 0.22 * math.sin(yaw))

    pose = HeadPose3D(
        cx=hcx, cy=hcy, R=R,
        yaw=yaw, pitch=pitch, roll=roll,
        stroke_px=float(info.get("stroke_px", 4.5)),
        face_bgr=tuple(int(v) for v in info.get("face_color", (251, 252, 252))),
        ex=ex, ey=ey, er=er, eh=eh, my=my, mw=mw,
        base_yaw=yaw, base_pitch=pitch, base_roll=roll,
        ear_safe_u_min=ear_safe_u_min, ear_safe_u_max=ear_safe_u_max,
        max_acting_shift_px=float(max_acting_shift_px),
    )
    if prev is not None and smooth > 0.0:
        k = float(np.clip(smooth, 0.0, 0.95))
        for fld in ("cx", "cy", "R", "yaw", "pitch", "roll", "base_yaw", "base_pitch", "base_roll",
                    "ex", "ey", "er", "eh", "my", "mw"):
            setattr(pose, fld, k * getattr(prev, fld) + (1.0 - k) * getattr(pose, fld))
    return pose


