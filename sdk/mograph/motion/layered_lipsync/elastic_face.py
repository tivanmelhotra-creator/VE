    if viseme == "L":
        return AestheticMouthSpec(open_h=(0.68 + 0.16 * en) * ex, stretch_w=0.84, bean_smile=0.42,
                                  pear_skew=0.18, upper_teeth=0.42, tongue=0.80, tongue_out=(var > 0.65))
    if viseme == "O":
        return AestheticMouthSpec(open_h=(0.74 + 0.20 * en) * ex, stretch_w=0.50 + 0.10 * var,
                                  bean_smile=-0.16, pear_skew=0.18, upper_teeth=0.34, tongue=0.54, dimple_tick=False)
