def prepare_hybrid_character_rig(cr: np.ndarray) -> dict[str, Any]:
    """
    Prepare a 100% artifact-free rig for colored/curly-haired 2D characters (both Front and 3/4 views):
      1. Detects the exact Face Skin component (enclosing 2 white scleras with cheek skin below),
         sampling `skin_bgr`, `hair_bgr` (for filled cream-blonde eyebrows), and `ink_bgr` (dark espresso outline).
      2. Erases ONLY the dark pupils inside the eye sockets (preserving the anti-aliased outer sclera rim and
         double-wing female eyelashes 100% untouched!).
      3. Erases the static filled eyebrows and static mouth to `skin_bgr` while protecting the forehead hair curl,
         the cute nose arc, and the under-chin shadow!
      4. Solves the 3D `HeadPose3D` (`yaw`, `pitch`, `roll`, `R`) from eye foreshortening and face contour.
    """
    H, W = cr.shape[:2]
    gray = cv2.cvtColor(cr, cv2.COLOR_BGR2GRAY)
    hsv = cv2.cvtColor(cr, cv2.COLOR_BGR2HSV)

    sclera_raw = ((hsv[:, :, 1] < 26) & (hsv[:, :, 2] > 228) & (gray >= 165)).astype(np.uint8)
    sn, slbl, sst, sce = cv2.connectedComponentsWithStats(sclera_raw, connectivity=4)

    non_ink = ((gray >= 140) & (sclera_raw == 0)).astype(np.uint8)
    non_ink_er = cv2.erode(non_ink, np.ones((3, 3), np.uint8))
    n, lbl, st, ce = cv2.connectedComponentsWithStats(non_ink_er, connectivity=4)

    face_comp_id = None
    best_score = -1
    eye_ids = []
    for i in range(1, n):
        x, y, w, h, a = st[i]
        if a < 1200 or x <= 1 or y <= 1 or x + w >= W - 1:
            continue
        comp_mask = (lbl == i).astype(np.uint8)
        cs, _ = cv2.findContours(comp_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        hull = cv2.convexHull(max(cs, key=cv2.contourArea))
        ha = cv2.contourArea(hull)
        comp_dil = cv2.dilate(comp_mask, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (25, 25)))
        enclosed = []
        for j in range(1, sn):
            sa = sst[j, 4]
            if 80 <= sa <= 0.35 * ha:
                sx, sy = sce[j]
                if cv2.pointPolygonTest(hull, (float(sx), float(sy)), False) >= 0:
                    bx_s, by_s, bw_s, bh_s, _ = sst[j]
                    cy_chk = min(H - 1, int(by_s + bh_s + 14))
                    if comp_dil[cy_chk, int(sx)] > 0:
                        enclosed.append(j)
        if len(enclosed) >= 2:
            score = len(enclosed) * 100000 + a
            if score > best_score:
                best_score = score
                face_comp_id = i
                eye_ids = enclosed

    if face_comp_id is None:
        raise ValueError("Could not locate dual-sclera face skin component in image")

    skin_comp = cv2.dilate((lbl == face_comp_id).astype(np.uint8), np.ones((3, 3), np.uint8))
    skin_bgr = tuple(int(v) for v in np.median(cr[skin_comp > 0], axis=0))

    ext_non_ink = np.zeros((H, W), np.uint8)
    hair_comp = np.zeros((H, W), np.uint8)
    brow_mask = np.zeros((H, W), np.uint8)
    eyes = sorted([sst[j][:4].tolist() + [int(sst[j, 4]), float(sce[j][0]), float(sce[j][1]), j] for j in eye_ids], key=lambda t: t[5])
    eL, eR = eyes[0], eyes[1]
    eyes_top_y = min(eL[1], eR[1])
    eyes_bot_y = max(eL[1] + eL[3], eR[1] + eR[3])
    eyes_mid_y = 0.5 * (eL[6] + eR[6])

    for i in range(1, n):
        if i == face_comp_id:
            continue
        bx, by, bw, bh, a = st[i]
        if 35 <= a <= 2500 and by + bh <= eyes_top_y + 24 and bx >= eL[0] - 18 and bx + bw <= eR[0] + eR[2] + 18:
            brow_mask |= cv2.dilate((lbl == i).astype(np.uint8), np.ones((3, 3), np.uint8))
        else:
            comp_i = cv2.dilate((lbl == i).astype(np.uint8), np.ones((3, 3), np.uint8))
            ext_non_ink |= comp_i
            if a > 5000 and by < H * 0.45:
                hair_comp |= comp_i

    hair_bgr = tuple(int(v) for v in np.median(cr[hair_comp > 0], axis=0)) if hair_comp.sum() > 0 else (198, 232, 250)
    ink_pixels = cr[(gray < 70) & (cv2.dilate(skin_comp, np.ones((7, 7), np.uint8)) > 0)]
    ink_bgr = tuple(int(v) for v in np.median(ink_pixels, axis=0)) if len(ink_pixels) > 0 else (18, 29, 53)

    eye_sockets = []
    sclera_col = (252, 254, 254)
    socket_union = np.zeros((H, W), np.uint8)
    pupil_erase = np.zeros((H, W), np.uint8)
    for e in eyes:
        bx, by, bw, bh, area, sx, sy, j_id = e
        sm = (slbl == j_id).astype(np.uint8)
        sm_closed = cv2.morphologyEx(sm, cv2.MORPH_CLOSE, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (39, 39)))
        cs_e, _ = cv2.findContours(sm_closed, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
        sock = np.zeros((H, W), np.uint8)
        cv2.drawContours(sock, [max(cs_e, key=cv2.contourArea)], -1, 1, -1)
        p_hole = cv2.dilate((sock > 0).astype(np.uint8) & (1 - sm), np.ones((5, 5), np.uint8)) & cv2.erode(sock, np.ones((3, 3), np.uint8))
        pupil_erase |= p_hole
        socket_union |= sock
        ys_e, xs_e = np.where(sock > 0)
        eye_sockets.append({
            "mask": sock,
            "contour": max(cs_e, key=cv2.contourArea).reshape(-1, 2),
            "bbox": (int(xs_e.min()), int(ys_e.min()), int(xs_e.max() - xs_e.min()), int(ys_e.max() - ys_e.min())),
            "cx": 0.5 * float(xs_e.min() + xs_e.max()),
            "cy": 0.5 * float(ys_e.min() + ys_e.max()),
            "rx": 0.5 * float(xs_e.max() - xs_e.min()),
            "ry": 0.5 * float(ys_e.max() - ys_e.min()),
        })

    upper_lash_probe = cv2.dilate(socket_union, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (29, 21))) & (1 - socket_union)
    is_female = bool(((gray < 80) & (upper_lash_probe > 0)).sum() > 0.16 * socket_union.sum())

    ext_guard = cv2.dilate(ext_non_ink, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (7, 7)))
    brow_erase = cv2.dilate(brow_mask, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (15, 11))) & (1 - ext_guard)

    eye_guard = cv2.dilate(socket_union, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (21, 21)))
    nose_box = np.zeros((H, W), np.uint8)
    nx0 = int(eL[0] + eL[2] * 0.88)
    nx1 = int(eR[0] + eR[2] * 0.22)
    ny0 = int(eyes_mid_y + 10)
    ny1 = int(eyes_bot_y + 18)
    if nx1 > nx0 and ny1 > ny0:
        nose_box[ny0:ny1, nx0:nx1] = 1
    nose_box &= (1 - eye_guard)

    ys_skin = np.where(skin_comp > 0)[0]
    max_skin_y = int(ys_skin.max()) if len(ys_skin) else H - 1
    face_closed = cv2.morphologyEx(skin_comp | socket_union | brow_mask, cv2.MORPH_CLOSE,
                                   cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (29, 29)))
    face_interior = face_closed & (1 - ext_guard)

    mouth_zone = np.zeros((H, W), np.uint8)
    mouth_zone[max(ny1 - 2, int(eyes_bot_y + 10)):max_skin_y - 3, :] = 1
    mouth_ink = ((gray < 175) & (mouth_zone > 0) & (face_interior > 0) & (nose_box == 0)).astype(np.uint8)
    ys_m, xs_m = np.where(mouth_ink > 0)
    mouth_center = (float(xs_m.mean()), float(ys_m.mean())) if len(xs_m) > 0 else (0.5 * (eL[5] + eR[5]), float(eyes_bot_y + 42))
    mouth_erase = cv2.dilate(mouth_ink, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (7, 7))) & face_interior
    mouth_erase[max_skin_y - 2:, :] = 0

    clean_hybrid = cr.copy()
    clean_hybrid[brow_erase > 0] = skin_bgr
    clean_hybrid[mouth_erase > 0] = skin_bgr
    clean_hybrid[pupil_erase > 0] = sclera_col

    cs_f, _ = cv2.findContours(face_closed, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    (hcx, hcy), (A, B), _ = cv2.fitEllipse(max(cs_f, key=cv2.contourArea))
    R = 0.25 * (A + B)
    sL, sR = eye_sockets[0], eye_sockets[1]
    emx = 0.5 * (sL["cx"] + sR["cx"])
    width_ratio = sR["rx"] / max(1.0, sL["rx"])
    if width_ratio < 0.78:
        yaw = math.acos(np.clip(width_ratio, 0.35, 1.0)) * 0.65
    elif (1.0 / max(0.1, width_ratio)) < 0.78:
        yaw = -math.acos(np.clip(1.0 / width_ratio, 0.35, 1.0)) * 0.65
    else:
        yaw = math.asin(np.clip((emx - hcx) / max(20.0, R), -0.65, 0.65))

    mx, my_px = mouth_center
    cx_eff = mx - R * math.sin(yaw)
    my_can = (my_px - hcy) / max(20.0, R)
    pose = HeadPose3D(
        cx=float(cx_eff), cy=float(hcy), R=float(R),
        yaw=float(yaw), pitch=0.0, roll=0.0,
        stroke_px=float(np.clip(R * 0.036, 2.5, 6.0)),
        face_bgr=skin_bgr,
        my=float(np.clip(my_can, 0.22, 0.68)),
        mw=0.60,
        base_yaw=float(yaw), base_pitch=0.0, base_roll=0.0,
    )

    forehead_curl_mask = np.zeros((H, W), np.uint8)
    forehead_curl_mask[:int(eyes_top_y + 12), :] = 1
    curl_clip = cv2.dilate(ext_non_ink & forehead_curl_mask, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (5, 5)))

    return {
        "clean_hybrid": clean_hybrid,
        "eye_sockets": eye_sockets,
        "mouth_center": mouth_center,
        "skin_bgr": skin_bgr,
        "hair_bgr": hair_bgr,
        "ink_bgr": ink_bgr,
        "pose": pose,
        "curl_clip": curl_clip,
        "face_interior": face_interior,
        "nose_box": nose_box,
        "is_female": is_female,
    }


def render_hybrid_character_expression(
    rig: dict[str, Any],
    E: AestheticEyeSpec,
    M: AestheticMouthSpec,
    shine: bool = True,
    acting_delta_yaw_deg: float = 0.0,
    acting_delta_pitch_deg: float = 0.0,
) -> np.ndarray:
    """
    Render an expression onto the final Female / Male character using the Hybrid Socket-Preserving + Elastic Engine,
    enforcing the Smart Anatomical Head-vs-Gaze Clamp (`max_acting_shift_px <= 8.0`).
    """
    safe_pose, safe_E = apply_smart_acting_turn(
        rig["pose"], E,
        requested_delta_yaw_deg=acting_delta_yaw_deg,
        requested_delta_pitch_deg=acting_delta_pitch_deg,
    )
    base = rig["clean_hybrid"].copy()
    H, W = base.shape[:2]

    if safe_E.happy_arc or safe_E.bot_lid < 0.68:
        for sock in rig["eye_sockets"]:
            scx, scy, srx, sry = sock["cx"], sock["cy"], sock["rx"], sock["ry"]
            sock_dil = cv2.dilate(sock["mask"], cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (17, 17)))
            y_cut = int(scy - 0.15 * sry) if safe_E.happy_arc else int(scy + max(0.15, safe_E.bot_lid - 0.10) * sry)
            bot_band = np.zeros((H, W), np.uint8)
            bot_band[max(0, y_cut):, :] = 1
            erase_rim = sock_dil & bot_band & rig["face_interior"] & (1 - rig["nose_box"])
            base[erase_rim > 0] = rig["skin_bgr"]

    surf = cairo.ImageSurface(cairo.FORMAT_ARGB32, W, H)
    ctx = cairo.Context(surf)
    ctx.set_antialias(cairo.ANTIALIAS_BEST)
    ctx.set_line_cap(cairo.LINE_CAP_ROUND)
    ctx.set_line_join(cairo.LINE_JOIN_ROUND)

    ink_b, ink_g, ink_r = [v / 255.0 for v in rig["ink_bgr"]]
    skin_b, skin_g, skin_r = [v / 255.0 for v in rig["skin_bgr"]]
    hair_b, hair_g, hair_r = [v / 255.0 for v in rig["hair_bgr"]]
    ink_col = (ink_r, ink_g, ink_b)
    skin_col = (skin_r, skin_g, skin_b)
    hair_col = (hair_r, hair_g, hair_b)

    st = safe_pose.stroke_px

    for idx, sock in enumerate(rig["eye_sockets"]):
        side = -1 if idx == 0 else +1
        in_s = -side
        scx, scy = sock["cx"], sock["cy"]
        srx, sry = sock["rx"], sock["ry"]
        cnt = sock["contour"]

        ctx.save()
        ctx.new_path()
        ctx.move_to(float(cnt[0, 0]), float(cnt[0, 1]))
        for pt in cnt[1:]:
            ctx.line_to(float(pt[0]), float(pt[1]))
        ctx.close_path()
        ctx.clip()

        if safe_E.happy_arc:
            ctx.set_source_rgb(*skin_col)
            ctx.paint()
        else:
            default_gaze_x = 0.22 if safe_pose.yaw >= -0.05 else -0.22
            gx = np.clip(safe_E.gaze_x + default_gaze_x, -0.58, 0.58)
            gy = np.clip(safe_E.gaze_y, -0.35, 0.35)
            pcx = scx + gx * srx * 0.52
            pcy = scy + gy * sry * 0.42
            p_scale = safe_E.pupil_scale / 0.68
            prx = srx * 0.30 * p_scale
            pry = sry * 0.44 * p_scale

            th = np.linspace(0.0, 2.0 * math.pi, 64, endpoint=False)
            ctx.new_path()
            ctx.move_to(float(pcx + prx * math.cos(0)), float(pcy + pry * math.sin(0)))
            for t_a in th[1:]:
                ctx.line_to(float(pcx + prx * math.cos(t_a)), float(pcy + pry * math.sin(t_a)))
            ctx.close_path()
            ctx.set_source_rgb(*ink_col)
            ctx.fill()

            if shine and safe_E.shine and p_scale >= 0.65:
                sh_x = pcx - 0.26 * prx
                sh_y = pcy - 0.28 * pry
                ctx.new_path()
                for k_i, t_a in enumerate(th):
                    px_s = sh_x + 0.24 * prx * math.cos(t_a)
                    py_s = sh_y + 0.24 * pry * math.sin(t_a)
                    if k_i == 0:
                        ctx.move_to(float(px_s), float(py_s))
                    else:
                        ctx.line_to(float(px_s), float(py_s))
                ctx.close_path()
                ctx.set_source_rgb(1.0, 1.0, 1.0)
                ctx.fill()

            if safe_E.top_lid > -0.68 or abs(safe_E.top_tilt) > 0.20:
                u = np.linspace(-1.15, 1.15, 48)
                ux = scx + u * srx
                lid_level = np.clip((safe_E.top_lid + 0.68) * 0.90 - 0.42, -0.85, 0.95)
                arch_curve = -0.14 * (1.0 - np.clip(u, -1.0, 1.0) ** 2) * (1.0 - max(0.0, lid_level))
                slant_curve = (u * in_s) * 0.34 * safe_E.top_tilt
                uy = scy + (lid_level + arch_curve + slant_curve) * sry

                ctx.new_path()
                ctx.move_to(float(scx - 1.2 * srx), float(scy - 1.3 * sry))
                ctx.line_to(float(scx + 1.2 * srx), float(scy - 1.3 * sry))
                for qx, qy in zip(ux[::-1], uy[::-1]):
                    ctx.line_to(float(qx), float(qy))
                ctx.close_path()
                ctx.set_source_rgb(*skin_col)
                ctx.fill_preserve()
                ctx.set_source_rgb(*ink_col)
                ctx.set_line_width(st * 1.15)
                ctx.stroke()

            if safe_E.bot_lid < 0.68:
                u = np.linspace(-1.15, 1.15, 48)
                ux = scx + u * srx
                bot_level = np.clip(safe_E.bot_lid, 0.15, 0.68)
                uy = scy + (bot_level - 0.12 * (1.0 - np.clip(u, -1.0, 1.0) ** 2)) * sry
                ctx.new_path()
                ctx.move_to(float(scx - 1.2 * srx), float(scy + 1.3 * sry))
                ctx.line_to(float(scx + 1.2 * srx), float(scy + 1.3 * sry))
                for qx, qy in zip(ux[::-1], uy[::-1]):
                    ctx.line_to(float(qx), float(qy))
                ctx.close_path()
                ctx.set_source_rgb(*skin_col)
                ctx.fill_preserve()
                ctx.set_source_rgb(*ink_col)
                ctx.set_line_width(st * 0.95)
                ctx.stroke()

        ctx.restore()

        ub = np.linspace(-1.0, 1.0, 44)
        u_out = ub * side
        bx = scx + ub * srx * 0.94
        lift_offset = (safe_E.brow_y + 1.42) * sry * 0.72 + safe_E.brow_asym * 0.22 * sry * side
        base_by = (scy - sry * 1.25) + lift_offset
        tilt_dy = (ub * in_s) * sry * 0.36 * (safe_E.brow_tilt + 0.06)
        arch_dy = -(1.0 - ub * ub) * sry * 0.34 * safe_E.brow_arch
        by_center = base_by + tilt_dy + arch_dy

        w_env = (1.0 - ub * ub) ** 0.52 * (1.0 - 0.20 * u_out)
        half_th = sry * 0.145 * w_env
        top_b = np.c_[bx, by_center - half_th]
        bot_b = np.c_[bx[::-1], (by_center + half_th * 0.65)[::-1]]
        brow_poly = np.vstack([top_b, bot_b])

        ctx.save()
        ctx.new_path()
        ctx.move_to(float(brow_poly[0, 0]), float(brow_poly[0, 1]))
        for pt in brow_poly[1:]:
            ctx.line_to(float(pt[0]), float(pt[1]))
        ctx.close_path()
        ctx.set_source_rgb(*hair_col)
        ctx.fill_preserve()
        ctx.set_source_rgb(*ink_col)
        ctx.set_line_width(st * 0.65)
        ctx.stroke()
        ctx.restore()

    draw_canonical_mouth(ctx, safe_pose, M)

    surf.flush()
    stride = surf.get_stride()
    arr = np.frombuffer(surf.get_data(), np.uint8).reshape(H, stride)[:, :W * 4].reshape(H, W, 4)
    bgra = arr.astype(np.float32) / 255.0

    curl_allow = (1.0 - rig["curl_clip"].astype(np.float32))[:, :, None]
    a = bgra[:, :, 3:4] * curl_allow
    col = bgra[:, :, :3] * curl_allow
    base_f = base.astype(np.float32) / 255.0
    return np.clip((col + base_f * (1.0 - a)) * 255.0 + 0.5, 0, 255).astype(np.uint8)
