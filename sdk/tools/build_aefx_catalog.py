"""
tools/build_aefx_catalog.py — MEASURE every motion / text preset → agent-readable catalogue
(sdk/mograph/aefx/presets/catalog.json + CATALOG.md).  The agent picks presets from measured data, not names.

motion: dur, ends_identity, peak_scale, peak_rot, travel (frame widths), blur, energy → tags
        soft / punchy / spin / 3d / blur / distort / travel / overshoot / settles-offset / stays-visible
text:   dur, props, units, random / wiggly / 3d / blur / decode tags
    python3 tools/build_aefx_catalog.py
"""
from __future__ import annotations

import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from mograph.aefx import motion as AM, textanim as TA   # noqa: E402


def motion_stats(p):
    W, H = 192, 108
    img = np.zeros((H, W, 3), np.uint8)
    img[30:78, 60:132] = 255
    T = np.linspace(0, p["dur"], 20)
    prev, energy, travel, sc = None, 0.0, 0.0, 1.0
    for t in T:
        o = AM.apply_preset(img, p, t)
        m = o[..., 0] > 60
        if m.any():
            ys, xs = np.nonzero(m)
            travel = max(travel, abs(xs.mean() - 96) / W, abs(ys.mean() - 54) / W)
            sc = max(sc, (xs.max() - xs.min() + 1) / 72.0)
        if prev is not None:
            energy += float(np.abs(o.astype(np.int16) - prev).mean())
        prev = o.astype(np.int16)
    rot = blur = 0.0
    for f in p["fx"]:
        for n, v in f["p"].items():
            vals = [r[1] for r in v["k"]] if isinstance(v, dict) else [v]
            if n in ("rotation", "swivel", "tilt"):
                rot = max(rot, max(abs(float(x)) for x in vals))
            if n == "blur":
                blur = max(blur, max(float(x) for x in vals))
    end = AM.apply_preset(img, p, p["dur"] + 0.01)
    ends_id = float(np.abs(end.astype(int) - img).mean()) <= 2.0
    end_vis = float(end[..., 0].mean() / img[..., 0].mean())
    e = energy / len(T)
    tags = [t for t, c in (("blur", blur > 10), ("distort", any(f["fx"] in ("wave_warp", "twirl") for f in p["fx"])),
                           ("3d", any(f["fx"] == "basic3d" for f in p["fx"])), ("spin", rot >= 180),
                           ("travel", travel > 0.3), ("overshoot", sc > 1.25), ("punchy", e > 9), ("soft", e < 3),
                           ("settles-offset", p["dir"] == "in" and not ends_id),
                           ("stays-visible", p["dir"] == "out" and end_vis > 0.1)) if c]
    return {"dur": round(p["dur"], 2), "ends_identity": ends_id, "peak_scale": round(sc, 2), "peak_rot": round(rot, 1),
            "travel": round(travel, 2), "blur": round(blur, 1), "energy": round(e, 1), "tags": tags}


def text_stats(p):
    props, units, rnd, wig = set(), set(), False, False
    for a in p["animators"]:
        props |= set(a["props"])
        for s in a["sel"]:
            units.add(s.get("based", "chars"))
            rnd |= bool(s.get("random"))
            wig |= s["type"] == "wiggly"
    tags = sorted(units) + [t for t, c in (("random", rnd), ("wiggly", wig), ("3d", p.get("is3d") or props & {"rx", "ry"}),
                                           ("blur", "blur" in props),
                                           ("decode", props & {"char_offset", "char_replace"})) if c]
    return {"dur": round(p.get("dur") or 1.0, 2), "props": sorted(props), "tags": tags}


def main():
    d = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "mograph", "aefx", "presets")
    cat = {"motion": {k: {"cat": p["cat"], "dir": p["dir"], **motion_stats(p)} for k, p in AM.library().items()},
           "text": {k: {"cat": p["cat"], "sub": p["sub"], "name": p["name"], **text_stats(p)}
                    for k, p in TA.library().items()}}
    with open(os.path.join(d, "catalog.json"), "w") as f:
        json.dump(cat, f, separators=(",", ":"), ensure_ascii=False)
    L = ["# AE-FX preset catalogue (generated by tools/build_aefx_catalog.py — do not edit by hand)", "",
         "Use: `\"fx\": [{\"motion\": KEY}]` on any layer/element · `\"preset\": KEY` on a v14 kinetic_title.",
         "LOOK before choosing: `python3 -m mograph.aefx sheet motion --cat Scale --dir in` · `... sheet text --cat Coding`.",
         "Tag `settles-offset` = IN preset that does NOT end at identity (intentional pose) — avoid for clean titles.", "",
         f"## Motion presets ({len(cat['motion'])})", "",
         "| key | cat | dir | dur s | tags | peak scale | rot° | travel | blur |", "|---|---|---|---|---|---|---|---|---|"]
    L += [f"| `{k}` | {v['cat']} | {v['dir']} | {v['dur']} | {' '.join(v['tags'])} | {v['peak_scale']} | {v['peak_rot']} | "
          f"{v['travel']} | {v['blur']} |" for k, v in cat["motion"].items()]
    L += ["", f"## Text presets ({len(cat['text'])})", "", "| key | category | name | dur s | props | tags |",
          "|---|---|---|---|---|---|"]
    L += [f"| `{k}` | {v['cat']}/{v['sub']} | {v['name']} | {v['dur']} | {'+'.join(v['props'])} | {' '.join(v['tags'])} |"
          for k, v in cat["text"].items()]
    with open(os.path.join(d, "CATALOG.md"), "w") as f:
        f.write("\n".join(L) + "\n")
    print("catalog:", len(cat["motion"]), "motion,", len(cat["text"]), "text →", os.path.abspath(d))


if __name__ == "__main__":
    main()
